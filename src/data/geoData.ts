export function getCountryOptions(): SelectOption[] {
  return ALL_COUNTRIES.map((c) => ({ value: c, label: c }));
}

export function getStateOptions(countryName: string): SelectOption[] {
  if (!countryName) return [];
  const states = STATES_BY_COUNTRY[countryName];
  if (states && states.length > 0) {
    return states.map((s) => ({ value: s, label: s }));
  }
  return [
    { value: `${countryName} Central State`, label: `${countryName} Central Region` },
    { value: `${countryName} Northern State`, label: `${countryName} Northern Region` },
    { value: `${countryName} Southern State`, label: `${countryName} Southern Region` },
    { value: `${countryName} Eastern State`, label: `${countryName} Eastern Region` },
    { value: `${countryName} Western State`, label: `${countryName} Western Region` },
    { value: 'Capital Territory', label: 'Capital Territory' },
  ];
}

export function getCityOptions(_countryName: string, stateName: string): SelectOption[] {
  if (!stateName) return [];
  const cities = CITIES_BY_STATE[stateName];
  if (cities && cities.length > 0) {
    return cities.map((c) => ({ value: c, label: c }));
  }
  return [
    { value: `${stateName} Central City`, label: `${stateName} Main Port / Hub` },
    { value: `${stateName} Logistics District`, label: `${stateName} Logistics Zone` },
    { value: `${stateName} Industrial Area`, label: `${stateName} Industrial Park` },
    { value: `${stateName} Commercial Hub`, label: `${stateName} Commercial District` },
  ];
}
